static Trnode* MakeNode(const Item* pi)								// Функция выделяет память под динамическую структуру. Функция принмает указатель pi на структуру типа Item (под новую структуру с данными о животном);
{
	Trnode* new_node;												// Создаем локальный указатель new_node указывающий на структуру типа Trnode;
	new_node = (Trnode*)malloc(sizeof(Trnode));						// Указателю new_node присваивается адрес выделенной памяти для струкутуры в куче. (Trnode*) - даем знать компилятору что работаем с типом струкутры Trnode. sizeof(Trnode) - определение размера струкутуры;
	if (new_node != NULL)											// Если функции malloc не удалось выделить память, то функция MakeNode() возвращает нулевой адрес на структуру Trnode;
	{
		new_node->item = *pi;										// new_node->item - указатель new_node обращается к переменной item типа структуры Item. И структуре Item копируются данные, на которые указывает указатель pi. Поля структуру Item заполняются данными о животном (имя, вид);
		new_node->left = NULL;										// new_node->left - указатель new_node обращается к указателю left поля struct trnode* left. И указателю left записывается нулевой адрес, для того чтобы обозначит, что у новой корневой (родительской) струткуры будет отсутствует узел с левой дочерней структурой, т.е. ее нет;
		new_node->right = NULL;										// new_node->right - указатель new_node обращается к указателю right поля struct trnode* right. И указателю right записывается нулевой адрес, для того чтобы обозначит, что у новой корневой (родительской) струткуры будет отсутствует узел с правой дочерней структурой, т.е. ее нет;
	}
	return new_node;												// Функция возвращает адрес на новую структру типа Trnode;
}

static Pair SeekItem(const Item* pi, const Tree* ptree)				// Функция ищет узел с животным в дереве. Принимает указатель pi на искомые данные Item и указатель ptree на дерево Tree, в котором проходит поиск. В конце возвращает пару указателей (родитель и цель);
{
	Pair look;														// Создаем локальную переменную look типа Pair, которая будет хранить два указателя: на родительский узел (parent) и на текущий целевой узел (child);
	look.parent = NULL;												// Изначально родитель равен NULL, так как поиск начинается с самого верха (корня), а у корня нет родителя;
	look.child = ptree->root;										// Записываем в child адрес корня дерева (ptree->root), делая корень стартовой точкой для проверки;
	while (look.child != NULL)										// Цикл проверяет, пока не достигнет в родительской структуре нулевого адреса дочерней структуры, т.е. дальше родитеской структуры ничего нет;
	{
		if (ToLeft(pi, &(look.child->item)))						// Функция ToLeft() определяет, нужно ли искать животное в левой ветви. Для этого она принимает адрес pi введенных данных Item и адрес поля item (карточки животного) внутри того узла дерева, на который указывает поле child переменной look структуры Pair. Знак & берет прямой адрес этой карточки;
		{															// Если функция вернет логическую 1 движемся дальше по левому узлу, в противном случае по правому узлу и блок if пропустится;
			look.parent = look.child;								// Указателю parent родительской структуры записывается адрес указателя child дочерней структуры. Получается дальше спускаемся по дереву вниз;
			look.child = look.child->left;							// Далее дочерняя структура становится родительской структурой и у нее есть такие же дочерние узлы. И этой структуре записывается адрес новой левой дочерней структуры. Сделали шаг по дереву вниз влево;
		}
		else if (ToRight(pi, &(look.child->item)))					// Функция ToRight() определяет, нужно ли искать животное в правой ветви. Для этого она принимает адрес pi введенных данных Item и адрес поля item (карточки животного) внутри того узла дерева, на который указывает поле child переменной look структуры Pair. Знак & берет прямой адрес этой карточки;
		{															// Если функция вернет логическую 1 движемся дальше по правому узлу, в противном случае по левому узлу и блок if пропустится;
			look.parent = look.child;								// Указателю parent родительской структуры записывается адрес указателя child дочерней структуры. Получается дальше спускаемся по дереву вниз;
			look.child = look.child->right;							// Далее дочерняя структура становится родительской структурой и у нее есть такие же дочерние узлы. И этой структуре записывается адрес новой правой дочерней структуры. Сделали шаг по дереву вниз вправо;
		}
		else												
			break;													// Если нашли точное совпадение, то произойдет выход из цикла while;
	}
	return look;													// Возвращаем структуру Pair. Если животное найдено, в child будет его адрес, а в parent — адрес ветки выше. Если не найдено, в child останется NULL;
}

