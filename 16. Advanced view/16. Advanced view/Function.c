// Абстрактные функции:
void InitializeTree(Tree* ptree)									// Инициализация дерева (самого первого);
{
	ptree->root = NULL;												// Указатель ptree обращается к полю Trnode* root структуры Tree, т.к. еще неизвестен следующий узел указателю root записывается нулевой адрес;
	ptree->size = 0;												// Указатель ptree обращается к полю int size и этому полю записывается значение 0;
}																	// Данная операция в этой функции делается, чтобы указатели не указывали на случайный (мусорный) адрес и количество улов было равно 0, а не какому либо случайному (мусорному) значению. Тем самым программа защищается от бага;

bool TreeIsEmpty(const Tree* ptree)									// Проверка дерева на свободное место;
{
	if (ptree->root == NULL)										// Указатель ptree обращается к полю Trnode* root структуры типа Tree, если указатель равен нулевому адресу, то дерево свободно (пустое);
		return true;												// Функция возвращает логическую 1;
	else															// Если указателю root присвоен адрес отличный от 0, в дереве имеются данные по животному (даже если это записано в структуре первого дерева);
		return false;												// Функция вернет логический 0;
}

bool TreeIsFull(const Tree* ptree)									// Проверка дерева на полностью занятые узлы;
{
	if (ptree->size == MAXITEMS)									// Указатель ptree обращается к полю int size структуры типа Tree, если переменная равна максимальному значению узлов (т.е. 10 животных), то место в дереве отсутствует;
		return true;												// Функция возвращает логическую 1;
	else															// Если переменная size меньше 10, то место в дереве есть; 
		return false;												// Функция вернет логический 0;
}

int TreeItemCount(const Tree* ptree)								// Функция возвращает количество узлов (сколько животных состоит в клубе);
{
	return ptree->size;												// Указатель ptree обращается к полю int size структуры типа Tree. Во время вызова, функция вернет значение, которое записано в переменной size, т.е. количество животных состоящих в клубе;
}

bool AddItem(const Item* pi, Tree* ptree)							// Функция добавляет информацию животного в узел и возвращает логическую 1 при успешном добавлении. Если не получилось добавить функция вернет логический 0;
{
	Trnode* new_node;												// Создаем указатель new_node на структуру типа Trnode, которое играет роль добавления нового животного в новый узел;
	if (TreeIsFull(ptree))											// Проверка на свободное место в дереве. Если нет места, выведется сообщение "Дерево переполнено" и функция  AddItem() завершится, вернув логический 0;
	{																
		fprintf(stderr, "Дерево переполнено\n");
		return false;
	}
	if (SeekItem(pi, ptree).child != NULL)							// Проверка на дублирование узла, функция SeekItem() ищет в дереве структуру (животное) с таким же именем и видом животного. Если узел находится с таким же именем и видом, то выводится сообщение "Попытка добавления дублированного элемента", вернув логический 0;
	{
		fprintf(stderr, "Попытка добавления дублированного элемента\n");
		return false;
	}
	new_node = MakeNode(pi);										// Функция MakeNode() добавляет в узел данные по животоному (добавляет данные структуры Item, на которую указвает указатель pi. При этом дочерним узлам left и right записывается нулевой адрес, чтобы сделать узел в дереве последним. При этом функция возвращает указатель (адрес) на структуру Trnode и этот адрес записывается указателю new_node;
	if (new_node == NULL)											// Если указателю не удалось записать адрес, то адрес будет нулевой, т.к. в функции MakeNode() используется функция malloc() и если не удастся выделить память в куче, функция вернет нулевой адрес;
	{
		fprintf(stderr, "Не удалось создать узел\n");				// Выведется сообщение "Не удалось создать узел" и функция  AddItem() вернет логический 0;
		return false;
	}
	ptree->size++;													// Указатель ptree обращается к полю int size структуры типа Tree. Происходит инкрементирование переменной на 1. Это означает, что удалось записать данные животного в узел;
	if (ptree->root == NULL)										// Указатель ptree обращается к полю Trnode* root структуры типа Trnode. Если указателю root нулевой адрес,
		ptree->root = new_node;										// запишется адрес новой структуры Trnode.
	else															// Если указателю root записан не нулевой адрес (то есть у дерева уже есть корень), вызовется функция AddNode(), которая принимает адрес нового узла (new_node) и адрес корня дерева (ptree->root). Корень служит стартовой точкой, от которой функция начнет спускаться по веткам.
		AddNode(new_node, ptree->root);								// Функция рекурсивно ищет свободное место ниже по дереву и определяет, к какому узлу и в какую ветку привязать новые данные (левую или правую).
	return true;													// Функция AddItem() возвращает логическую 1 в случае успешного добавления животного в новую струткуру типа Trnode;
}

bool InTree(const Item* pi, const Tree* ptree)						// Функция проверяет на наличие данных о животном в дереве (ищет узел (структуру Trnode) в дереве, которая содержит данные о животном);
{
	return (SeekItem(pi, ptree).child == NULL) ? false : true;		// Функция возвращает результат - существует или не существует животное в списке. Для поиска используется функция SeekItem(), которая принимает указатель pi (адрес) на структуру типа Item и указатель ptree (адрес) на структуру типа Tree.
}																	// Функция SeekItem() возвращает структуру типа Pair. Структура Pair обращается к полю child. Если функция нашла данные животного (структуры типа Item), функция InTree() вернет логическую 1, если не найдет логический 0;

bool DeleteItem(const Item* pi, Tree* ptree)						// Функция удаляет структуру типа Trnode из дерева, для поиска вводится структура типа Item (данные о животном);
{
	Pair look;														// Создаем переменную look типа структуры Pair, в которой содержатся поле корневого узла parent и дочернее поле корневого узла child;
	look = SeekItem(pi, ptree);										// Функция SeekItem() возвращает структуру типа Pair. Адрес этой структуры записывается указателю look;
	if (look.child == NULL)											// Проверяем есть ли данная струткура типа Item с данными о животном. Если в дочернем указателе child адрес нулевой, функция DeleteItem() вернет логический 0 - удалять нечего;
		return false;
	if (look.parent == NULL)										// Проверяем есть ли данная струткура типа Item с данными о животном. Если в корневом указателе parent адрес нулевой, это значит, что узел является самым верхним, над ним отсутствует родительский узел. И далее вызовится функция DeleteNode(), 
		DeleteNode(&ptree->root);									// которая принмает адрес указателя ptree, который обращается к полю Trnode* root (указателю на главный корень дерева). Функция DeleteNode() определит какой узел сделать главным; 
	else if (look.parent->left == look.child)						// Проверяем есть ли данная струткура типа Item с данными о животном в левой струткуре. look.parent->left - указатель parent переменной look типа струткуры Pair обращается к указателю left на струткуру Trnode, т.е. какой адрес левого дочернего узла записан. look.child - смотрим какой адрес записан у дочернего узла.
		DeleteNode(&look.parent->left);								// Если адрес равны, вызывается функция DeleteNode(), которая принимает адрес указателя left (у родительского узла берем адрес дочернего узла). Функция DeleteNode() определит какой узел подставить вместо удаленного узла с данными о животном (вместо удаленной струткуры, заменить на другую);
	else															// Если узел нашелся, но он не является главным корнем и не висит у родителя слева, значит, методом исключения он гарантированно висит справа
		DeleteNode(&look.parent->right);							// Функция DeleteNode() принимает адрес дочернего правого узла и удаляет его. И определится какой узел подставится вместо удаленного узла с данными о животном (вместо удаленной струткуры, заменится на другую);
	ptree->size--;													// Указатель ptree указвает на поле int size структуры типа Tree. Переменная уменьшается на единицу. Т.е. уменьшаем количество животных состоящих в клубе;
	return true;													// Функция возвращает логическую единицу в случае успеха удаления структуры;
}

void Traverse(const Tree* ptree, void(*pfun)(Item item))			// Функция принимает адрес указателя ptree на структуру Tree и указатель на любую функцию, которая принимает переменную item типа структуры Item (данные по животному);
{																	// В данной программе выводятся данные по животным, состоящим в клубе;
	if (ptree != NULL)												// Проверяем существование самой структуры управления деревом (картотеки). Если картотека создана в памяти, то адрес ptree не равен нулю;
		InOrder(ptree->root, pfun);									// Указатель ptree обращается к полю Trnode* root структуры Tree. Функция InOrder() принимает адрес этого корня (даже если он NULL) и указатель pfun на функцию (в данной программе это функция printitem()); 
}

void DeleteAll(Tree* ptree)											// Функция удаляет все узлы (структуры), принимает указатель (адрес) ptree на структуру типа Tree (где хранятся все данные по животным состоящим в клубе);
{
	if (ptree != NULL)												// Проверяем существование самой структуры управления деревом (картотеки). Если картотека создана в памяти, то адрес ptree не равен нулю;
	{
		DeleteAllNodes(ptree->root);								// Функция DeleteAllNodes() принимает указатель (адрес) root поля Trnode* root структуры типа Tree. Функция удаляет все струткруры (все базу данных по клубу);
		ptree->root = NULL;											// Указатель ptree обращается к указателю поля Trnode* root структуры типа Tree. И указтелю root записывается нулевой адрес, т.е. дерево существует. но оно пустое;
		ptree->size = 0;											// Указатель ptree обращается к переменной поля int size структуры типа Tree. Переменной size присваивается 0, т.е. в клубе 0 животных;
	}	
}

// Определения локальных функций: 
static void InOrder(const Trnode* root, void(*pfun)(Item item))		// Функция принимает указатель root на струткуру Trnode (указатель на корневой узел - дерево) и казатель на любую функцию, которая принимает переменную item типа структуры Item (данные по животному);
{
	if (root != NULL)												// Проверяем, существует ли текущий узел дерева (не упёрлись ли мы в конец ветки);
	{
		InOrder(root->left, pfun);									// Функция InOrder() вызывает сама себя, но принимает адрес левой дочерней структуры в родительской структуре и указатель pfun на функцию (в данной программе это функция printitem()). Самовызов функции (рекурсия) не закончится, пока не дойдет до конца левой ветки, где адрес равен NULL;
		(*pfun)(root->item);										// Вызывается функция (в данном случае printitem), на которую указывает указатель pfun. Функция принимает струкутру item типа структуры Item (примает данные по животному);
		InOrder(root->right, pfun);									// Функция InOrder() вызывает сама себя, но принимает адрес правой дочерней структуры в родительской структуре и указатель pfun на функцию (в данной программе это функция printitem()). Самовызов функции (рекурсия) не закончится, пока не дойдет до конца правой ветки, где адрес равен NULL;
	}																// Принцип функции InOrder(), заключается в том, что начало идет с самого верха дерева, до самого низа по левой стороне, когда левая сторона закончилась и упёрлась в NULL, функции InOrder() принмать нечего, и она пропустится до строки (*pfun)(root->item) и происходит печать самой нижней струткуры, 
}																	// При обратной рекурсии уже напечатается строка корневой структуры, затем программа полезет в правую дочернюю структуру и тоже напечатает текст. 		
																	// Получается в обратном направлении получается путь лево, вверх, вправо, вверх, вверх, вправо, вверх, вверх и т.д.;  

static void DeleteAllNodes(Trnode* root)							// Функция для удаления всего дерева. Функция принимает указатель root указывающий на структуру типа Tnode;
{
	Trnode* pright;													// Создаем локальный указатель pright указывающий на структуру типа Trnode;
	if (root != NULL)												// Проверяем, существует ли текущий узел дерева (не упёрлись ли мы в конец ветки);
	{
		pright = root->right;										// root->right - указатель root обращается к полю struct trnode* right структуры Trnode. Указателю pright записывается адрес правой дочерней структуры right;
		DeleteAllNodes(root->left);									// Функция DeleteAllNodes() вызывает сама себя, принимая указатель left текущей структуры Trnode, на которую указывает root. Функция будет вызывать сама себя, пока не дойдет до конца левой ветки, где адрес равен NULL;
		free(root);													// Происходит очистка выделенной памяти под корневую структуру;
		DeleteAllNodes(pright);										// Функция DeleteAllNodes() вызывает сама себя, принимая указатель pright, которой раннее записался адрес правой структуры в корневой (родительской) структуре;
	}																// Принцип функции DeleteAllNodes(), заключается в том, что начало идет с самого верха дерева, до самого низа по левой стороне, когда левая сторона закончилась и упёрлась в NULL, функции DeleteAllNodes() принмать нечего, и она пропустится до строки free(root) и происходит удаление выделенной памяти под левую структуру,
}																	// При обратной рекурсии уже дойдет до удаления правой структуры, т.к. сохраненный адрес pright передается в следующий самовызов. Получается в обратном направлении получается путь лево - удалили, вверх, вправо - удалили, вверх - удалили, вверх, вправо - удалили, вверх - удалили, вверх и т.д.;  

static void AddNode(Trnode* new_node, Trnode* root)					// Функция для добавления узла. Принимает указатель new_node на новую структуру типа Trnode, которую нужно добавить и указатель root, который указывает на структуру типа Trnode;
{
	if (ToLeft(&new_node->item, &root->item))						// При проверки функция ToLeft(), принимает адрес на новую структуру item, которая содержит информацию о животном и адрес на структуру item, где уже находится информация о животном. Функция ToLeft() определяет в какой узел записать новое животное. Запись идет в алфавитном порядке;
	{
		if (root->left == NULL)										// Проверка условия. Если в родительской структуре в поле struct trnode* left указателю left записан нулевой адрес, то дочерней структуры левого узла нет;
			root->left = new_node;									// То по указаетлю left запишется адрес новой структуры new_node. Т.е. у родительской струткуры появилася левая дочерняя структура;
		else														// Если указаетелю записан адрес, то левая дочерняя структура существует и произойдет вновь вызов функции AddNode() (рекурсия), т.е. функция .
			AddNode(new_node, root->left);							// Функция принимает адрес по указателю new_node новой структуры и адрес дочерней левой структуры по указателю left, который содержит корневая (родительская) структура. Рекурсия будет происходить до тех пор, пока указатель left не упрется в нулевой адрес. Т.е. функция ToLeft() решила определить структуру слева;
	}
	else if (ToRight(&new_node->item, &root->item))					// При проверки функция ToRight(), принимает адрес на новую структуру item, которая содержит информацию о животном и адрес на структуру item, где уже находится информация о животном. Функция ToRight() определяет в какой узел записать новое животное. Запись идет в алфавитном порядке;
	{
		if (root->right == NULL)									// Проверка условия. Если в родительской структуре в поле struct trnode* right указателю right записан нулевой адрес, то дочерней структуры правого узла нет;
			root->right = new_node;									// То по указателю right запишется адрес новой структуры new_node. Т.е. у родительской струткуры появилася правая дочерняя структура;
		else
			AddNode(new_node, root->right);							// Функция принимает адрес по указателю new_node новой структуры и адрес дочерней правой структуры по указателю right, который содержит корневая (родительская) структура. Рекурсия будет происходить до тех пор, пока указатель right не упрется в нулевой адрес. Т.е. функция ToRight() решила определить структуру справа;
	}
	else															// Если функции ToLeft() и ToRight() не определили в какой узел добавлять структуру.
	{
		fprintf(stderr, "Ошибка местоположения в AddNode()\n");		// Выведется сообщение об ошибке с кодом 1 и программа завершится, при условии, что введем совершено одинаковые данные по животному;
		exit(1);
	}
}

