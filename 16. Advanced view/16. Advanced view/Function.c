// Использование массива структур (и для остальных программ):

char* s_gets(char* st, int n)				// Функция принимает адрес начала массива и размер массива, возвращает адрес на начало массива, т.е. вернется указатель на начало текста;
{
	char* ret_val;							// Создаем указатель типа char для того, чтобы дать адрес начала текста (начало массива);
	char* find;								// Создаем указатель типа char для символа;
	ret_val = fgets(st, n, stdin);			// Функция fgets() используется для ввода текста, 1 аргумент - массив, куда запишется текст, 2 аргумент - размер массива, 3 аргумент - стандартный поток ввода. Указателю ret_val запишется адрес начала массива (начало текста);
	if (ret_val)							// Если ввели только ввод, указателю ret_val записался бы адрес символа \n. Пропустится в случае ошибки программы или конец файла EOF;
	{
		find = strchr(st, '\n');			// Функция strchr() ищет символ новой строки, если находит, то записывает адрес указателю find. Если не нашел запишется нулевой адрес;
		if (find)							// Если нашли символ новой строки, блок if выполнит действие, если не найдет (только в случае, если текст превысил размер массива), блок if пропустится;
			*find = '\0';					// Указателю перезаписывается символ новой строки на символ конца строки;
		else								// Если не найден символ новой строки (только в случае, если текст превысил размер массива), то символы, которые не влезли в размер, очистятся;
			while (getchar() != '\n')		// Произойдет очистка буфера ввода от этих символов;
				continue;
	}
	return ret_val;							// Функция возвращает адрес начала массива (возвращает текст). Вернет NULL в случает ошибки программы или конец файла EOF;
}


