		// ШАГ 1: Копирует адрес правой ветки удаляемого узла:
		temp->right = (*ptr)->right;								// Через временный указатель temp структуры Trnode обращаемся к указателю right, этому указателю записывается адрес указателя right старой структуры;
		// ШАГ 2: Сохраняем адрес удаляемого узла:
		temp = *ptr;												// Временному указателю temp (адрес) на структуру типа Trnode записывается адрес структуры типа Trnode;
		// ШАГ 3: Родитель теперь указывает на левого потомка удаляемого узла:
		*ptr = (*ptr)->left;										// Через указатель *ptr получаем доступ к полю struct trnode* left структуры Trnode и этому указателю left записываем адрес дочерней левой структуры;
		// ШАГ 4: Физически удаляем старый узел:
