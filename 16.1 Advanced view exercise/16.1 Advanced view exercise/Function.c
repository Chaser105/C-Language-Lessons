		DeleteAllNodes(root->left);                                 // Рекурсивно уходим в левую ветку, чтобы полностью очистить все узлы, расположенные слева;
		DeleteAllNodes(root->right);                                // Рекурсивно уходим в правую ветку, чтобы полностью очистить все узлы, расположенные справа;
		free(root);                                                 // Когда оба потомка (левый и правый) гарантированно удалены, безопасно освобождаем память самого текущего узла;
