	char stroka[] = "Добрый вечер";
	unsigned u = 5468;
	short sh = 58;
	short num = 345;
	short mnum = -65724;
	float n1 = 3.0;
	double n2 = 3.0;
	long n3 = 2000000000;
	long n4 = 1234567890;
	int bph2o = 212;
	int rv;
	int number = 249;
	intmax_t big_val = 9223372036854775807LL;			// Максимум для 64 бит;
	uintmax_t u_big_val = 18446744073709551615ULL;
	double d_pi = 3.14159265358979323846;
