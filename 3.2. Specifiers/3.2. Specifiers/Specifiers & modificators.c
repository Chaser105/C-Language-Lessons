	printf("%ld, %ld. \n", n3, n4);						  // В данной строке результат получится корректный;
	printf("%ld, %ld, %ld, %ld. \n\n", n1, n2, n3, n4);	  // Для чисел с плавающей запятой спецификатор "%ld", как и просто "%d" не используется, ответ будет ноль или вовсе непредсказуем. А для "n3", "n4" ответ будет хоть и будет корректен, но т.к. в функции прописанный неверные спецификаторы, вывод тоже может быть непредсказуем; 
	/* Для первых двух спецификаторов %e всё хорошо: они берут по 8 байт от n1 и n2.
	Для третьего %e функция снова забирает 8 байт.
	Но в очереди на этом месте лежит n3 (всего 4 байта)!
	Результат: printf берет 4 байта числа n3 и «склеивает» их со следующими 4 байтами, которые принадлежат числу n4.
	
	%ld (который хочет 4 байта) пытается прочитать n1 (3.0), которое занимает 8 байт: Число 3.0 в памяти выглядит как: 00 00 00 00 (первые 4 байта) и 40 08 00 00 (вторые 4 байта).
	Первый %ld забирает первые 4 байта - видит все нули - выводит 0. Второй %ld забирает оставшиеся 4 байта от того же самого числа n1 - видит 40 08 00 00 - в десятичной системе это 1074266112. 
	Главный вывод: Числа в компьютере — это просто последовательность битов. Спецификатор — это «трафарет». Если трафарет (%e — 8 байт) наложить на данные неправильного размера (long — 4 байта), 
	он захватит часть соседнего числа, и мы получим бессмысленный результат.
	*/

	// Вывод длинных строк:
	printf("Вот один из способов вывода ");
	printf("длинной строки. \n");
