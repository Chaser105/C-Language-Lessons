	printf("%a: число с плавающей запятой, шестнадцатеричной цифры и р-запись. \n", a);
	printf("%A: число с плавающей запятой, шестнадцатеричной цифры и P-запись. \n", A);
	printf("%c: вывод символа. \n", ch);
	printf("%d: вывод десятичного числа. \n", decimal);
	printf("%e: вывод числа с плавающей запятой, экспоненциальное представление. \n", expon);
	printf("%E: вывод числа с плавающей запятой, экспоненциальное представление. \n", EXPON);
	printf("%f: вывод числа с плавающей запятой. \n", drob);
	printf("%g: в зависимости от значения использует спецификатор f или e. \n"														// Спецификатор "%g" считает только первые 6 цифр значащими, остальные отбрасывает, получится результат "4869.87". Если будет число "4869875.289425", то результат "4,86988e+06";
		   "Спецификатор е применяется если показатель степени меньше -4 либо больше или равен указанной точности. \n", d);			// Если будет число "4869875.289425", то результат "4,86988e+06";
	printf("%G: в зависимости от значения использует спецификатор f или E. \n"														// Спецификатор "%G" считает только первые 6 цифр значащими, остальные отбрасывает, получится результат " 54.259" (после округления 6 число "0" отбросится).
			"Спецификатор Е применяется если показатель степени меньше -4 либо больше или равен указанной точности. \n", D);		// Если будет число "5425896314.7", то результат "5.4259Е+09";
	printf("%i: вывод десятичного числа. \n", decimal);
	printf("%o: вывод числа без знака в восьмеричной форме. \n", octa);
	printf("%p: указатель. \n", ptr);
	printf("%s: вывод символьной строки. \n", stroka);
	printf("%u: вывод десятично целого числа без знака. \n", u);
	printf("%x: вывод шестнадцатеричного целого чиисла без знака, используются шестнадцатериччные цифры 0f.\n", decimal);
	printf("%X: вывод шестнадцатеричного целого чиисла без знака, используются шестнадцатериччные цифры 0f.\n", octa);
	printf("%%: вывод знака процент. \n\n");

	// Модификаторы для спецификаторов:
	// Ширина поля целыми числами, флаги форматирования (пробелы), алгебраические знаки:
	// Тип int:
	printf("*%d*: без указания пробела. \n", decimal);
	printf("*%2d*: на выходе пробелов не будет, т.к. число занимает 2 пробела. \n", decimal);
	printf("*%10d*: получаем отступ слева 8 пробелов, еще 2 пробела забирает значение. \n", decimal);
	printf("*%-9d*: получаем 7 пробелов справа, 2 пробела занимает значение. \n", decimal);
	printf("%ld: как тип long, %9lu: как тип long и слева будет 5 отступов. \n\n", u, u);			// Тоже самое с модификатором "ll" ("%lld", "%12llu") тип long long;

	printf("*%x: шестнадцатеричный эквивалент, %X: шестнадцатеричный эквивалент, %#x: шестнадцатеричная форма*. \n", 77, 77, 77);
	printf("**%d**: без отступов, **% d**: с одним отступом, **  %d**: с двумя отступами, с алгебраическим знаком -. \n", 46, 46, -46);
	printf("**%4d**: 3 пробела перед числом, **%6.3d**: 2 нуля перед числом, 3 пробела перед значением, \n" 
			" **%05d**: 4 нуля перед числом, **%06.3d**: 2 нуля перед числом, 3 пробела перед значением. \n\n", 7, 7, 7, 7);

	// Тип short:
	printf("*%hu*: без уазания пробела, *%hx*: шестнадцатеричный эквивалент, *%5.3hd*: два отступа слева, еще 3 знимает значение, при этом первый знак 0.\n", sh, sh, sh);
	printf("*%2hu*: на выходе пробелов не будет, т.к. число занимает 2 пробела. \n", sh);
	printf("*%5hu*: получаем отступ слева 3 пробела, еще 2 пробела забирает значение. \n\n", sh);
	printf("num как тип short и тип unsigned short: %hd и %hu. \n", num, num);				// Некорректная запись, но диапазона типа "short" хватает, что со знаком спецификатор %hd, что без знака спецификатор %hu - программа работать будет;
	printf("-num как тип short и тип unsigned short: %hd и %hu. \n", mnum, mnum);			// Некорректная запись. 65724 в HEX - FFFFFFFFFFFEFF44 (8 байт), знаковый тип "short" ("%hd)" имеет 2 байта, плучается обрезка первых 6 байт, осталось FF44 (1111111101000100, первый знак переменной "-"), в результате значение "-188". Или можно представить - -65724 + 65536 = -188;
																							// Спецификатор "%hu" - беззнаковый тип "short" (2 байта) знак "-" уже отбрасывается, тоже происходит обрезка значения, получилось FF44 (1111111101000100), результат "65348". Программа будет рабать не корректно. Или можно представить - 65724 - 65536 = 188;
	printf("num как тип int и тип char: %d и %c. \n", num, num);							// Значение "345" в диапазон типа "int" помещается, программа будет работать корректно. Если применить спецификатор "%c" (тип "char", который имеет размер 1 байт), произойдет обрезка старших байтов (345 - 0х0159, останется 0х59 или 89). В результате вывдется символ согласно ASCII "Y";
	printf("NUMBER как тип int, short и char: %d, %hd, %c. \n\n", NUMBER, NUMBER, NUMBER);	// Значение "65724" в диапазон типа "int" помещается, программа будет работать корректно. Если применить специффикатор "hd" (тип "short", размером 2 байта), произойдет обрезка старших байтов (65724 - 0х0100ВС, останется 0х00ВС или 188).
																							// Если применить спецификатор "%c" (тип "char", который имеет размер 1 байт), произойдет обрезка старших байтов (65724 - 0х0100ВС, останется 0хВС или 188). В результате выводится символ ASCII "?", вернее компилятору неизветен такойд знака, т.е. знак не определен. Программа не будет корректно работать;

	// Тип unsigned char, signed char:
	printf("Как int равняется %d. \n", number);
	printf("Как char (hh) равняется %hhd: 249 это 0b000000011111001, старшие 2 байта обрежутся, останется 0b11111001, т.к. тип данных со знаком, то 8 бит единица это знак -. \n\n", number);
	printf("%hhu: в диапазон типа char помещается, %hhx: представление в шестнадцатеричной форме, %5.hhd - знаковый тип char, в диапазон не помещется (результат со знаком -), слева отступа, еще 2 отступа занимает результат. \n\n", number, number, number);


	// Ширина поляс с числами с плавающей запятой, алгебраические знаки, пробелы, 
	printf("*%f: без модификатра.* \n", VALUE);
	printf("*%e: без модификатра.* \n", VALUE);
	printf("*%4.2f: отступ слева 4 пробела, но значение занимает больше, ширина автоматически будет больше. Округление до 2 значений после запятой*. \n", VALUE);
	printf("*%3.1f: отступ слева 3 пробела, но значение занимает больше, ширина автоматически будет больше. Округление до 1 значения после запятой*. \n", VALUE);
	printf("*%12.3f: отступ слева 4 пробела, остальные 8 - значение. 3 значения после запятой*. \n", VALUE);
	printf("*%15.3E: отступ слева 6 пробелов, остальные 9 - значение. Представление значения в экспоненциальной форме*. \n", VALUE);
	printf("*%+11.2f*: перед значением ставится алгебраический знак +. Отступ слева 3 пробела, остальные 8 - значение, включая знак +. Округление до 2 значений после запятой*. \n", VALUE);
	printf("*%012.2f: перед значением будет 5 нулей. Округление до 2 значений после запятой*. \n\n", VALUE);

	printf("Обычный double:    %.18f. \n", d_pi);
	printf("Длинный long double: %.18Lf. \n", ld_pi);
	printf("Длинный long double, отступы слева и 8 знаков после запятой: %28.8Lf. \n\n", ld_pi);

	// Форматирование строк:
	printf("[%2s]: строка выведется целиком, спецификатор расширяет поле автоматически, двойка здесь не играет роли. \n", TEXT);
	printf("[%30s]: строка выведется целиком, добавится 4 отступа слева. \n", TEXT);
