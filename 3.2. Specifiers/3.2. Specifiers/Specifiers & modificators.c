	printf("В шестнадцатеричном виде и отступами слева: %20jx. \n\n", u_big_val);

	// Размер используется специально для типа "size_t":
	// Раньше приходилось гадать: использовать %u, %lu или %llu. Модификатор "z" решил эту проблему — он всегда выбирает правильный размер автоматически.
	// sizeof возвращает значение типа size_t
	// %zu — спецификатор для вывода size_t
