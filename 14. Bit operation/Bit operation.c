	// Перед записью новых данных целевое поле в памяти ОБЯЗАТЕЛЬНО нужно обнулить. 
	// Если этого не сделать, старые единицы смешаются с новыми и данные испортятся.
	// * Как работает: Оператор '~' инвертирует маску поля, превращая её в набор единиц
	//   с нулями строго на позициях нужного нам поля.
	// * Результат: При побитовом И (&) единицы маски сохраняют все остальные настройки 
	//   окна без изменений, а нули маски принудительно стирают биты этого поля в 0.
	//
	// ЭТАП 2: ЗАПИСЬ ДАННЫХ («КАРАНДАШ») — ОПЕРАТОР '|='
	// Когда на месте целевого поля образовались чистые нули, туда вписывается новый режим.
	// * Как работает: В константе нового режима (например, B_DOTTED) единицы стоят только
	//   в целевых позициях, а во всех остальных позициях числа стоят нули.
	// * Результат: При побитовом ИЛИ (|) новые биты без помех ложатся на очищенное место.
