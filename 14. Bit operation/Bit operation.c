	/*
		Вычитание из 256:
		Нужно вычесть комбинацию битов отрицательного числа из 9-битовой комбинации 100000000 (это число 256)». Компьютерная память «зациклена».
		Если к максимальному числу, которое вмещается в 8 бит (это 255, или 1111 1111), прибавить 1, произойдет переполнение. 
		Восьмибитная ячейка сбросится в 0000 0000, а единица «улетит» в несуществующий 9-й бит. 
		То есть для 8-битной ячейки числа 256 и 0 — это одно и то же. Поэтому, чтобы узнать, какое отрицательное число закодировано, можно мысленно вычесть этот код из 256:
		Пример с кодом 1111 1111: В режиме «без знака» этот код равен 255. Вычитаем его из 256 (256 - 255 = 1).
		Поскольку первый бит был единицей, добавляем минус. Получаем -1.

		Пример с кодом 1000 0000 (самый запутанный момент): В режиме «без знака» это число 128. Вычитаем по формуле: (256 - 128 = 128). 
		Первый бит равен 1, значит, число отрицательное. Получаем -128. В старом методе (величина со знаком) код 1000 0000 означал бы просто «минус ноль». 
		А метод дополнения до двух позволил использовать эту «пустую» комбинацию с пользой и расширить диапазон до -128.
		Как это понять проще (без вычитания из 256)? Чтобы не ломать голову над вычитанием из 256, программисты используют простое правило «Переверни биты и прибавь 1».
		Если вы видите код 11111111 и знаете, что это число со знаком: Видим 1 в начале — значит, число точно отрицательное. 
		Переворачиваем все биты (0 меняем на 1, 1 на 0): получаем 00000000. Прибавляем единицу: получаем 00000001 (это цифра 1). Вспоминаем про минус из первого шага. Ответ: -1.
	*/

	/*
		Дробные числа:
		Дробное число состоит из из двух деталей: Мантисса (двоичная дробь) — это само значимое число. 
		Экспонента — это «команда» для запятой, показывающая, на сколько шагов и в какую сторону её нужно сдвинуть.
		Пример «на пальцах», допустим, компьютеру нужно сохранить число 2,5 в десятичной системе. Сначала он переводит его в двоичный код. 2,5 — это 2 + 0,5. 
		В двоичном виде это пишется как 10,1 (где 10 — это двойка, а, 1 — это половинка). Теперь компьютер двигает запятую так, чтобы перед ней осталась только одна единица: 1,01.
		Поскольку мы сдвинули запятую на 1 знак влево, компьютер дописывает множитель: (2*(1)). 
		В итоге в память компьютера запишутся две вещи: Двоичная дробь (мантисса): 101 Экспонента: 1 (сдвиг на 1 позицию).
		Когда программе понадобится это число, процессор посмотрит на экспоненту (1), сдвинет запятую обратно и получит исходное 10,1 (то есть 2,5).

		На примере числа 3,054:
		Мантисса 3 равна 11 (целое число). Берем дробную часть - 0,054. Начинаем сравнивать 0,054 с 0,5. 0,5 больше 0,054, ставим 0. 
		Далее 0,5 делим на 2, это 0,25. 0,054 сравниваем с 0,25. 0,25 больше 0,054, ставим 0.
		Далее 0,25 делим на 2, это 0,125. 0,054 срвавниваем с 0,125. 0,125 больше 0,054, ставим 0.
		Далее 0,125 делим на 2, это 0,0625. 0,054 сравниваем с 0,0624. 0,0625 больше 0,054, ставим 0.
		Далее 0,0625 делим на 2, это 0,03125. 0,054 сравниваем с 0,03125. 0,03125 меньше 0,054, ставим 1.
		Дальше считаем остаток: 0,054 - 0,03125 = 0,02275. И этот остаток также сравниваем:
		Далее  0,03125 делим на 2, это 0,015625. 0,02275 сравниваем с 0,015625. 0,015625 меньше 0,02275, ставим 1. 
		Считаем остаток 0,02275 - 0,015625 = 0,007125. 
		Далее 0,015625 делим на 2, это 0,0078125. 0,007125 сравниваем с 0,0078125. 0,015625 больше 0,007125, ставим 0. 
		Когда компютер закончит считать, итоговый набор значений 11,0000110........., переставляет запятую к 1 левой 1 - 1,10000110.........
		Компьютер обрежет либо на 23 знаке значения, либо на 52, в зависимости какой тип применен float или double.
		Если значение не делится без остатка, то после запятой будет бесконечное число значений.
		Далше компьютер отсекает первую 1 и записывает в память 10000110......... (оставшуюся часть). Первую 1 компьютер выбрасывает.
		При использовании этого значения компьютер по умолчанию подставит эту 1.

		Сравним +3,054 и -3,054 в памяти компьютера (тип float): Ячейка памяти float делится на 3 части (всего 32 бита):
		Знак — 1 бит. Экспонента — 8 бит. Мантисса (хвост дроби) — 23 бита. 
		Для числа +3,054: [0] [Экспонента] [10000110...] (первый бит равен 0) 
		Для числа +3,054 Знак (1 бит): 0. Экспонента (8 бит): 10000000Мантисса (23 бита): 10000110001101001011110 (рассчитанный хвост, обрезанный до 23 знаков).

		Для числа -3,054:[1] [Экспонента] [10000110...] (первый бит равен 1)
		Для числа -3,054 Всё абсолютно то же самое, меняется только самый первый бит с нуля на единицу: 
		Знак (1 бит): 1 Экспонента (8 бит): 10000000 Мантисса (23 бита): 10000110001101001011110В памяти это лежит так: 11000000010000110001101001011110;

		+3.054 ->  0   10000000     10000110001101001011110
		-3.054 ->  1   10000000     10000110001101001011110
		           ▲      ▲                   ▲
		         Знак  Экспонента     Мантисса (хвост)
	*/

	/*
		Восьмеричная система счисления:

		| Восьмеричная (8) | Двоичная триада (2) |
		| :--------------: | :-----------------: |
		|        0         |         000         |
		|        1         |         001         |
		|        2         |         010         |
		|        3         |         011         |
		|        4         |         100         |
		|        5         |         101         |
		|        6         |         110         |
		|        7         |         111         |

		Число 0462 представляется как 0001 0011 0010. Число занимает 2 байта. 0011 0010 - младший байт, 0001 - старший байт.
		Число 0462 эквивлентно десятичному числу 306. Проверка 4*8^2 + 6*8^1 + 1*8^0 = 256 + 48 + 8 = 306.

		Если в числе есть цифра 8 или 9 - это уже не восьмиричное число, а десятичное или шестнадцатиричное может быть.
	*/

