	/*
	=====================================================================
		 МЕХАНИЗМ СОПРЯЖЕНИЯ КОНТРОЛЛЕРОВ ЧЕРЕЗ СДВИГИ (<< и >>)
	=====================================================================
	 Главный закон: Чтобы две разные системы поняли друг друга, инженеры
	 создают общую инструкцию (Спецификацию), где жестко прописан номер
	 бита для каждого датчика (Например: Дверь = Бит №3).

	 1. НА СТОРОНЕ ПЕРЕДАТЧИКА (Китай):
		- Китаец знает из инструкции, что дверь сидит на 3-й позиции.
		- Команда (1 << 3) сдвигает единицу влево, упаковывая её строго
		  в 3-й бит отправляемого байта (00001000).

	 2. НА СТОРОНЕ ПРИЕМНИКА (Германия):
		- Немец принимает байт (00001000) и знает, что надо смотреть 3-й бит.
		- Команда (принятый_байт >> 3) сдвигает биты обратно вправо на 3 шага.
		- Сигнал двери из глубины числа физически перемещается в самый край (00000001).
		- Программа видит чистую единицу и понимает, что датчик сработал.

	 ВЫВОД: Сдвиги влево (<<) и вправо (>>) работают как универсальный лифт.
	 Передатчик поднимает бит на нужный "этаж" провода, а приемник опускает
	 его обратно для проверки. Это полностью исключает путаницу компиляторов.
	=====================================================================
	*/

